const SAFE_PROTOCOL = /^(https?|mailto):/i;

/**
 * Returns the URL when it is http(s)/mailto, otherwise "". Whitespace and control
 * characters are stripped before the check so " \tJaVa\nscript:" style tricks fail.
 */
export function safeUrl(url: string | null | undefined): string {
  if (!url) return "";
  const cleaned = Array.from(url)
    .filter((ch) => {
      const c = ch.codePointAt(0) ?? 0;
      return !(c <= 0x20 || (c >= 0x7f && c <= 0x9f) || (c >= 0x200b && c <= 0x200f) || c === 0x2028 || c === 0x2029 || c === 0xfeff);
    })
    .join("");
  return SAFE_PROTOCOL.test(cleaned) ? url.trim() : "";
}

const linkClass = "break-words text-primary-text underline underline-offset-2 hover:no-underline [overflow-wrap:anywhere]";

// Same-page footnote anchors generated by remark-gfm (ids carry the clobber prefix).
const FOOTNOTE_HREF = /^#user-content-[A-Za-z0-9_-]+$/;

/**
 * urlTransform: http(s)/mailto, plus remark-gfm's own footnote fragments and
 * "user:<id>" mention hrefs. Mentions are checked first so they survive to the
 * `a` override, which never turns them into a clickable href.
 */
export function transformUrl(url: string): string {
  const mentionId = mentionIdFromHref(url);
  if (mentionId) return `user:${mentionId}`;
  return FOOTNOTE_HREF.test(url) ? url : safeUrl(url);
}

/** Display names of mentionable members, by user id (from the DB, never from the body). */
export type MentionNames = Record<string, string>;

const mentionClass =
  "rounded-md bg-primary-soft px-1 py-px font-medium text-primary-text [overflow-wrap:anywhere] box-decoration-clone";

/**
 * A "user:<id>" link: a non-interactive chip with the DB name when the id is
 * a current member (in `names`), otherwise the written text as plain text.
 */
function Mention({ id, names, children }: { id: string; names: MentionNames; children?: ReactNode }) {
  if (Object.hasOwn(names, id)) {
    return (
      <span className={mentionClass} data-mention={id}>
        @{names[id]}
      </span>
    );
  }
  return <span>{children}</span>;
}

type LinkExtras = Pick<ComponentProps<"a">, "id" | "aria-describedby" | "aria-label">;

function SafeLink({ href, children, ...extras }: { href?: string; children?: ReactNode } & LinkExtras) {
  if (href && FOOTNOTE_HREF.test(href)) {
    return (
      <a href={href} className={linkClass} {...extras}>
        {children}
      </a>
    );
  }
  const safe = safeUrl(href);
  if (!safe) return <span id={extras.id}>{children}</span>;
  return (
    <a href={safe} target="_blank" rel="noopener noreferrer nofollow" className={linkClass}>
      {children}
    </a>
  );
}

const NO_MENTIONS: MentionNames = {};

// Minimal structural view of the hast nodes react-markdown passes as `node`.
type HastNode = {
  type: string;
  tagName?: string;
  value?: string;
  properties?: Record<string, unknown>;
  children?: HastNode[];
};

function containsImage(node: HastNode | undefined): boolean {
  return Boolean(node?.children?.some((c) => (c.tagName === "img" ? true : containsImage(c))));
}

/** Text of a hast subtree, with images replaced by their alt text. */
function hastText(node: HastNode): string {
  if (node.type === "text") return node.value ?? "";
  if (node.tagName === "img") return typeof node.properties?.alt === "string" ? node.properties.alt : "";
  return (node.children ?? []).map(hastText).join("");
}

type AnchorProps = ComponentProps<"a"> & { node?: unknown };

function anchor(
  { href, children, node, id, "aria-describedby": describedBy, "aria-label": label }: AnchorProps,
  names: MentionNames,
) {
  // Mentions first: a "user:" href is never handed to SafeLink.
  const mentionId = mentionIdFromHref(href);
  if (mentionId) {
    return (
      <Mention id={mentionId} names={names}>
        {children}
      </Mention>
    );
  }
  const extras = { id, "aria-describedby": describedBy, "aria-label": label };
  // A linked image ("[![alt](img)](url)", badge syntax): the img override would
  // render a second <a> inside this one, which breaks hydration. Use the text.
  if (containsImage(node as HastNode | undefined)) {
    const text = hastText(node as HastNode).trim();
    return (
      <SafeLink href={href} {...extras}>
        {text || safeUrl(href) || href}
      </SafeLink>
    );
  }
  return (
    <SafeLink href={href} {...extras}>
      {children}
    </SafeLink>
  );
}

/** Headings are demoted (h1 -> h3 ...) so user content never breaks the page outline. */
function heading(Tag: "h3" | "h4" | "h5" | "h6", className: string) {
  return function Heading({ children, id, className: incoming }: ComponentProps<"h3">) {
    return (
      <Tag id={id} className={cn("mt-5 mb-2 font-semibold tracking-tight first:mt-0", className, incoming)}>
        {children}
      </Tag>
    );
  };
}

const baseComponents: Components = {
  h1: heading("h3", "text-xl"),
  h2: heading("h4", "text-lg"),
  h3: heading("h5", "text-base"),
  h4: heading("h6", "text-sm"),
  h5: heading("h6", "text-sm"),
  h6: heading("h6", "text-sm text-muted-foreground"),
  p: ({ children }) => <p className="my-3 first:mt-0 last:mb-0 [overflow-wrap:anywhere]">{children}</p>,
  a: (props) => anchor(props, NO_MENTIONS),
  // Remote images are never loaded (tracking pixels, layout abuse): show a plain link instead.
  img: ({ src, alt }) => {
    const safe = safeUrl(typeof src === "string" ? src : "");
    if (!safe) return <span>{alt}</span>;
    return <SafeLink href={safe}>{alt || safe}</SafeLink>;
  },
  ul: ({ children, className }) => (
    <ul
      className={cn(
        "my-3 list-disc space-y-1 pl-6",
        className?.includes("contains-task-list") && "list-none pl-0",
      )}
    >
      {children}
    </ul>
  ),
  ol: ({ children }) => <ol className="my-3 list-decimal space-y-1 pl-6">{children}</ol>,
  li: ({ children, className, id }) => (
    <li
      id={id}
      className={cn(
        "[overflow-wrap:anywhere]",
        className?.includes("task-list-item") && "flex items-start gap-2",
      )}
    >
      {children}
    </li>
  ),
  input: ({ type, checked }) =>
    type === "checkbox" ? (
      <input
        type="checkbox"
        checked={Boolean(checked)}
        disabled
        readOnly
        aria-label={checked ? "Tamamlandı" : "Tamamlanmadı"}
        className="mt-1 size-4 shrink-0 accent-primary"
      />
    ) : null,
  blockquote: ({ children }) => (
    <blockquote className="my-3 border-l-4 border-border pl-4 text-muted-foreground italic">{children}</blockquote>
  ),
  hr: () => <hr className="my-5 border-border" />,
  strong: ({ children }) => <strong className="font-semibold">{children}</strong>,
  pre: ({ children }) => (
    <pre className="my-3 max-w-full overflow-x-auto rounded-lg bg-muted p-3 font-mono text-[0.85em] leading-relaxed">
      {children}
    </pre>
  ),
  code: ({ children, className }) =>
    className ? (
      <code className={cn("font-mono", className)}>{children}</code>
    ) : (
      <code className="rounded bg-muted px-1 py-0.5 font-mono text-[0.85em] [overflow-wrap:anywhere]">{children}</code>
    ),
  table: ({ children }) => (
    <div className="my-3 max-w-full overflow-x-auto rounded-lg border border-border">
      <table className="w-full border-collapse text-left text-sm">{children}</table>
    </div>
  ),
  th: ({ children }) => <th className="border-b border-border bg-muted px-3 py-2 font-semibold">{children}</th>,
  td: ({ children }) => <td className="border-b border-border px-3 py-2 align-top">{children}</td>,
};

function componentsFor(names: MentionNames | undefined): Components {
  if (!names) return baseComponents;
  return { ...baseComponents, a: (props) => anchor(props, names) };
}

/** Footnote labels in Turkish (remark-rehype defaults are English). */
const remarkRehypeOptions = {
  footnoteLabel: "Dipnotlar",
  footnoteBackLabel: (referenceIndex: number, rereferenceIndex: number) =>
    `İçeriğe dön (${referenceIndex + 1}${rereferenceIndex > 1 ? `-${rereferenceIndex}` : ""})`,
};

/**
 * Safe markdown (CommonMark + GFM). No raw HTML, only http(s)/mailto links
 * (plus "user:<id>" mentions, rendered as chips and never as links),
 * images become links, headings are demoted. Text nested deeper than
 * MAX_MARKDOWN_NESTING renders as plain text (deep nesting overflows the stack).
 */
export function Markdown({
  text,
  className,
  mentions,
}: {
  text: string;
  className?: string;
  /** Members that may render as mention chips. Without it every mention is plain text. */
  mentions?: MentionNames;
}) {
  const wrapper = cn("min-w-0 max-w-full text-sm leading-relaxed break-words", className);
  if (isMarkdownTooDeep(text)) {
    return (
      <div className={wrapper}>
        <p className="whitespace-pre-wrap [overflow-wrap:anywhere]">{text}</p>
      </div>
    );
  }
  return (
    <div className={wrapper}>
      <ReactMarkdown
        remarkPlugins={[remarkGfm]}
        remarkRehypeOptions={remarkRehypeOptions}
        components={componentsFor(mentions)}
        urlTransform={transformUrl}
        skipHtml={false}
      >
        {mentionsForRender(text)}
      </ReactMarkdown>
    </div>
  );
}
